// Local integration simulation. Does NOT create or run a real ChatGPT scheduled task.
// Optional browser test: install Playwright separately; not needed for npm test.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const out = new URL('../artifacts/external-briefing-test/', import.meta.url);
await fs.mkdir(out, { recursive: true });
const base = 'http://127.0.0.1:3217';
const results = [];
const record = (name, status, detail) => { results.push({ name, status, detail }); console.log(status, name, detail || ''); };
const server = spawn(process.execPath, ['dev.js'], { cwd: new URL('..', import.meta.url), env: { ...process.env, PORT: '3217', ASSISTANT: 'chatgpt', ICLOUD_USERNAME: '', ICLOUD_APP_PASSWORD: '', APP_PASSWORD: 'demo', MCP_TOKEN: 'demo' }, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
let seq = 0;
const mcp = async (name, args = {}) => {
  const r = await fetch(base + '/mcp/demo', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: ++seq, method: 'tools/call', params: { name, arguments: args } }) });
  const data = await r.json();
  assert.equal(r.status, 200);
  assert.ok(!data.result.isError, JSON.stringify(data));
  return JSON.parse(data.result.content[0].text);
};
const saveDaily = async markdown => {
  const r = await fetch(base + '/api/actions/daily-briefing', { method: 'POST', headers: { Authorization: 'Bearer demo', 'Content-Type': 'application/json' }, body: JSON.stringify({ markdown }) });
  assert.equal(r.status, 200); return r.json();
};
try {
  await once(server.stdout, 'data');
  const today = (await mcp('get_today')).today;
  const ev = await mcp('create_event', { title: '[테스트] 주간 업무 회의', category: 'Work', startDate: today, startTime: '10:00', endTime: '11:00' });
  await mcp('update_event', { id: ev.created.id, startTime: '10:30', endTime: '11:30' });
  await mcp('edit_topic', { op: 'create', name: 'Vesper 배포 준비 · 테스트', tag: 'Vesper', brief: 'GitHub 공개 및 개인 Vercel 배포 준비', target: today });
  await mcp('add_task', { title: '예약 실행과 브리핑 저장 점검', topic: 'Vesper', dueDate: today, dueTime: '18:00' });
  const context = await mcp('get_briefing');
  assert.ok(JSON.stringify(context).includes('주간 업무 회의'));
  assert.ok(JSON.stringify(context).includes('Vesper 배포 준비'));
  record('Calendar create/update + project context', 'PASS', 'MCP HTTP requests, demo storage.');
  const old = '# 일정 브리핑 · 로컬 테스트 1차\n\n- 10:30 주간 업무 회의\n- 18:00 예약 실행과 브리핑 저장 점검\n\n테스트 데이터이며 실제 ChatGPT 예약 결과가 아닙니다.';
  await saveDaily(old);
  browser = await chromium.launch({ ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}), headless: true });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, timezoneId: 'Asia/Seoul', serviceWorkers: 'block' });
  const page = await ctx.newPage();
  await page.route('https://**/*', route => route.abort());
  const pageErrors = []; page.on('pageerror', err => pageErrors.push(err.message));
  await page.goto(base);
  await page.locator('#pw').fill('demo');
  await page.locator('#loginForm button').click();
  await page.locator('#app').waitFor({ state: 'visible' });
  await page.locator('#bellBtn').click();
  await page.locator('#noteView').waitFor();
  assert.match(await page.locator('#noteView').innerText(), /1차/);
  await page.waitForTimeout(500);
  await page.screenshot({ path: new URL('01-mobile-daily-initial.png', out).pathname });
  // Simulate an external scheduled writer while this page stays open.
  const due = Date.now() + 1000;
  await new Promise(r => setTimeout(r, Math.max(0, due - Date.now())));
  const actual = Date.now();
  await saveDaily('# 일정 브리핑 · 로컬 테스트 2차\n\n- 10:30 주간 업무 회의 (수정된 시각 확인)\n- 18:00 예약 실행과 브리핑 저장 점검\n\n새 결과 저장 완료. 실제 ChatGPT 예약 실행은 별도 검증이 필요합니다.');
  const login = await fetch(base + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{"password":"demo"}' });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const note = await (await fetch(base + '/api/notes/daily', { headers: { cookie } })).json();
  assert.match(note.note.text, /2차/);
  record('Simulated delayed daily write + readback', 'PASS', `Local timer lateness ${actual - due} ms. This is not ChatGPT timing evidence.`);
  console.log('Waiting 35 real seconds with the calendar open to check automatic updates.');
  await new Promise(resolve => setTimeout(resolve, 35000));
  const stale = (await page.locator('#noteView').innerText()).includes('1차');
  assert.equal(stale, false, 'New external briefing should replace the displayed note');
  record('Daily automatic update while open', 'PASS', 'New external result displayed without manual refresh within 35 seconds.');
  await page.waitForTimeout(500);
  await page.screenshot({ path: new URL('02-mobile-daily-updated.png', out).pathname });
  await page.locator('[data-close]').click();
  await page.locator('#refreshBtn').click();
  await page.waitForResponse(r => r.url().endsWith('/api/notes/daily'));
  await page.locator('#bellBtn').click();
  await page.waitForFunction(() => document.querySelector('#noteView')?.textContent.includes('2차'));
  record('Daily after manual refresh', 'PASS');
  await page.waitForTimeout(500);
  await page.screenshot({ path: new URL('03-mobile-daily-refreshed.png', out).pathname });
  await page.locator('[data-close]').click();
  await mcp('save_briefing', { markdown: '# 업무 브리핑 · 로컬 테스트\n\n## Vesper 배포 준비\n- 최우선: 예약 실행 기록과 실패 재시도 설계\n- 일정 브리핑 자동 갱신 문제 확인\n- 18:00 저장 점검 마감\n\n테스트 데이터 · MCP로 저장한 결과입니다.' });
  await page.locator('#sheet').waitFor({ state: 'hidden' });
  await page.evaluate(() => window.dispatchEvent(new WheelEvent('wheel', { deltaX: 150, deltaY: 0 })));
  await page.locator('#workstream').waitFor({ state: 'visible' });
  await page.locator('#wsBrief').waitFor({ state: 'visible' });
  await page.locator('#wsBrief').click();
  await page.waitForFunction(() => document.querySelector('#noteView')?.textContent.includes('업무 브리핑'));
  record('Workstream MCP write and mobile rendering', 'PASS');
  await page.waitForTimeout(500);
  await page.screenshot({ path: new URL('04-mobile-workstream.png', out).pathname });
  await page.locator('[data-close]').click();
  await page.locator('#sheet').waitFor({ state: 'hidden' });
  await page.evaluate(() => window.dispatchEvent(new WheelEvent('wheel', { deltaX: -150, deltaY: 0 })));
  await page.locator('#catBtn').click();
  await page.locator('#sheetBody').getByRole('button', { name: '설정', exact: true }).click();
  assert.equal(await page.locator('#assistantSetting, #newSchedule, #scheduleForm').count(), 0);
  record('Settings use fixed server assistant and external scheduling', 'PASS');
  await page.waitForTimeout(500);
  await page.screenshot({ path: new URL('05-mobile-settings.png', out).pathname });
  record('Browser JavaScript errors', pageErrors.length ? 'FAIL' : 'PASS', pageErrors.join('; '));
} finally {
  if (browser) await browser.close();
  server.kill('SIGTERM');
  await fs.writeFile(new URL('results.json', out), JSON.stringify({ testedAt: new Date().toISOString(), mode: 'Local demo + mobile Chrome viewport. No real ChatGPT scheduled task, iPhone, Vercel or calendar credentials.', results }, null, 2));
}
